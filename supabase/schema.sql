-- BugHunt initial schema. Run in the Supabase SQL editor.
create extension if not exists pgcrypto;
create table if not exists public.projects (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 slug text not null unique,
 description text,
 logo_url text,
 accent_color text not null default '#426b53',
 is_public boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.reports (
 id uuid primary key default gen_random_uuid(),
 project_id uuid not null references public.projects(id) on delete cascade,
 report_number bigint generated by default as identity,
 title text not null,
 description text not null,
 category text not null default 'Other',
 priority text not null default 'Medium' check (priority in ('Low','Medium','High','Critical')),
 status text not null default 'Open' check (status in ('Open','In progress','Resolved','Closed')),
 reporter_name text,
 reporter_email text,
 page_url text,
 browser text,
 operating_system text,
 screen_size text,
 attachment_path text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists reports_project_created_idx on public.reports(project_id, created_at desc);
create index if not exists reports_status_idx on public.reports(status);
alter table public.projects enable row level security;
alter table public.reports enable row level security;
-- Public project directory is readable; public users can submit reports only to public projects.
create policy "Public can view public projects" on public.projects for select using (is_public = true);
create policy "Public can submit reports to public projects" on public.reports for insert with check (
 exists (select 1 from public.projects p where p.id = project_id and p.is_public = true)
);
